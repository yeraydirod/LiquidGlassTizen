"""Regenerate launcher/logos.js from Simple Icons (CC0 icon data; brands keep their trademarks).

  python3 tools/fetch_logos.py

Some brands were removed from newer Simple Icons releases, so each slug pins the
newest version that still has it.
"""

import json
import os
import re
import urllib.request

LATEST = "16.35.0"
SLUGS = {
    "youtube": LATEST,
    "netflix": LATEST,
    "spotify": LATEST,
    "stremio": LATEST,
    "max": LATEST,
    "appletv": LATEST,
    "plex": LATEST,
    "twitch": LATEST,
    "crunchyroll": LATEST,
    "paramountplus": LATEST,
    "tubi": LATEST,
    "jellyfin": LATEST,
    "primevideo": "13.0.0",
    "hulu": "9.0.0",
}
OUT = os.path.join(os.path.dirname(__file__), "..", "launcher", "js", "logos.js")


def main():
    logos = {}
    for slug, ver in SLUGS.items():
        url = f"https://cdn.jsdelivr.net/npm/simple-icons@{ver}/icons/{slug}.svg"
        svg = urllib.request.urlopen(url, timeout=20).read().decode()
        path = re.search(r'<path d="([^"]+)"', svg).group(1)
        logos[slug] = path
        print(f"{slug:<14} {ver}")
    with open(OUT, "w") as f:
        f.write("// Generated by tools/fetch_logos.py from Simple Icons (CC0). ")
        f.write("Trademarks belong to their owners.\n")
        f.write("window.LOGOS = " + json.dumps(logos, indent=0) + ";\n")
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
